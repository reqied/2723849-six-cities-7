import { Container } from 'inversify';
import {TYPES} from './shared/types/di.type.js';
import {PinoLogger} from './shared/logger/pino-logger.js';
import type { ILogger } from './shared/logger/logger.interface.js';
import {Application} from './application.js';
import {AppConfig, config} from './shared/config/config.js';
import { ImportCommand } from './cli/commands/import.command.js';
import { GenerateCommand } from './cli/commands/generate.command.js';
import {CLIApplication} from './cli/cli-application.js';
import {HelpCommand} from './cli/commands/help.command.js';
import {VersionCommand} from './cli/commands/version.command.js';
import {TSVFileReader} from './shared/file-reader/tsv-file-reader.js';
import {IDatabaseClient} from './shared/database-client/database-client.interface.js';
import {MongoDatabaseClient} from './shared/database-client/mongo-database-client.js';
import {IUserService} from './shared/modules/user/user-service.interface.js';
import {Model} from 'mongoose';
import {UserEntity, UserModel} from './shared/modules/user/user.model.js';
import {UserService} from './shared/modules/user/user.service.js';
import {IOfferService} from './shared/modules/offer/offer-service.interface.js';
import {OfferEntity, OfferModel} from './shared/modules/offer/offer.model.js';
import {OfferService} from './shared/modules/offer/offer.service.js';

export const container = new Container();
container.bind<ILogger>(TYPES.Logger).to(PinoLogger).inSingletonScope();
container.bind(Application).toSelf().inSingletonScope();
container.bind<AppConfig>(TYPES.Config).toConstantValue(config);
container.bind(ImportCommand).toSelf();
container.bind(GenerateCommand).toSelf();
container.bind(CLIApplication).toSelf();
container.bind(HelpCommand).toSelf();
container.bind(VersionCommand).toSelf();
container.bind(TSVFileReader).toSelf();
container.bind<IDatabaseClient>(TYPES.DatabaseClient).to(MongoDatabaseClient).inSingletonScope();
container.bind<IUserService>(TYPES.UserService).to(UserService).inSingletonScope();
container.bind<Model<UserEntity>>(TYPES.UserModel).toConstantValue(UserModel);
container.bind<IOfferService>(TYPES.OfferService).to(OfferService).inSingletonScope();
container.bind<Model<OfferEntity>>(TYPES.OfferModel).toConstantValue(OfferModel);
